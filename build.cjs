const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = __dirname;
const pages = require('./src/pages.json');
const metadata = require('./package.json');
const licenseBanner = fs.readFileSync(path.join(root,'LICENSE'),'utf8').trim().split(/\r?\n/).map(line=>'// '+line).join('\n');

function localVersion(date = new Date()) {
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-CA', {
    timeZone:'Asia/Shanghai',year:'numeric',month:'2-digit',day:'2-digit',
    hour:'2-digit',minute:'2-digit',second:'2-digit',hourCycle:'h23',
  }).formatToParts(date).map(part=>[part.type,part.value]));
  return `${parts.year}-${parts.month}-${parts.day} ${parts.hour}:${parts.minute}:${parts.second}`;
}
function releaseVersion() {
  const assert = require('node:assert/strict');
  assert.match(metadata.version,/^[1-9]\d*$/,'Release version must be a positive integer: 1, 2, 3, ...');
  const headings = [...fs.readFileSync(path.join(root,'CHANGELOG.md'),'utf8').matchAll(/^## (.+)$/gm)].map(match=>match[1]);
  for (const heading of headings) assert.match(heading,/^[1-9]\d*$/,'Changelog versions must be positive integers');
  assert.equal(headings[0],metadata.version,'Latest changelog version must match package.json');
  for (let i=1;i<headings.length;i++) {
    assert.equal(BigInt(headings[i-1]),BigInt(headings[i])+1n,'Changelog versions must increase by one');
  }
  return metadata.version;
}
function versionPlugin(fixedVersion) {
  let version;
  return {name:'broadcast-version',setup(build) {
    build.onStart(()=>{version=fixedVersion ?? localVersion();});
    build.onLoad({filter:/[\\/]src[\\/]common[\\/]version\.js$/},()=>({
      contents:'export const version = '+JSON.stringify(version)+';',loader:'js',
    }));
    build.onEnd(result=>{
      if (result.errors.length) return;
      const stamp=source=>source.replace('// '+metadata.name+'\n','// '+metadata.name+' version: '+version+'\n');
      if (result.outputFiles) {
        for (const output of result.outputFiles) output.contents=Buffer.from(stamp(output.text));
      } else {
        const file=build.initialOptions.outfile;
        fs.writeFileSync(file,stamp(fs.readFileSync(file,'utf8')));
      }
      for (const output of Object.values(result.metafile.outputs)) output.bytes+=Buffer.byteLength(' version: '+version);
    });
  }};
}
function options(page, version) {
  if (page && !pages.includes(page)) throw new Error('Unknown page: '+page+'. Available: '+pages.join(', '));
  const entry = page ? {stdin:{contents:
    "import {startDispatcher} from './common/index.js';\nimport * as page from './WebPage/"+page+"/module.js';\nstartDispatcher({"+page+":page});",
    resolveDir:path.join(root,'src'),sourcefile:'debug-'+page+'.js'}}
    : {entryPoints:[path.join(root,'src/entry.js')]};
  return {...entry,absWorkingDir:root,bundle:true,splitting:false,format:'iife',platform:'browser',
    target:['chrome100'],charset:'utf8',legalComments:'none',sourcemap:false,metafile:true,loader:{'.css':'text'},
    banner:{js:'// '+metadata.name+'\n'+licenseBanner+'\n// Third-party material: see THIRD_PARTY_NOTICES.md.\n// GENERATED by esbuild. Maintain src/; do not edit this file.\n// Native document-created injection; no browser module loader is required.'},
    plugins:[versionPlugin(version)],outfile:page?path.join(root,'debug',page+'.js'):path.join(root,'BroadcastListScript.js')};
}
function writeMetafile(page,result) {
  fs.mkdirSync(path.join(root,'verification'),{recursive:true});
  fs.writeFileSync(path.join(root,'verification',page?'build-'+page+'.json':'build-production.json'),JSON.stringify(result.metafile,null,2)+'\n');
}
async function build({page,write=true,version}={}) {
  const result=await esbuild.build({...options(page,version),write});
  if(write)writeMetafile(page,result);
  return result;
}
async function check({release=false}={}) {
  const assert = require('node:assert/strict');
  const vm = require('node:vm');
  const crypto = require('node:crypto');
  const scopes = require('./src/page-scopes.json');
  assert.equal(new Set(pages).size,pages.length,'Page IDs must be unique');
  assert.deepEqual(scopes.map(scope=>scope.id),pages,'Page scopes and build IDs must agree');
  const committed = fs.readFileSync(path.join(root,'BroadcastListScript.js'),'utf8');
  const version = committed.split(/\r?\n/,1)[0].replace('// '+metadata.name+' version: ','');
  const official = releaseVersion();
  if (release) assert.equal(version,official,'Run pnpm run build:release before submitting or releasing');
  else if (version!==official) assert.match(version,/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/,'Invalid bundle version');
  assert.equal(localVersion(new Date('2026-10-13T16:00:05Z')),'2026-10-14 00:00:05','Local versions must use Beijing time');
  const result = await build({write:false,version});
  assert.equal(result.outputFiles.length,1,'Production must be a single file');
  const source = result.outputFiles[0].text;
  new vm.Script(source,{filename:'BroadcastListScript.js'});
  assert.equal(source,committed,'Production bundle is stale. Run pnpm run build (local) or pnpm run build:release (before submitting).');
  assert.equal(source,(await build({write:false,version})).outputFiles[0].text,'Build must be deterministic for the same version');
  const runtimeVersion = source.match(/var version = ("[^"]+");/);
  assert(runtimeVersion,'Bundle must contain the shared runtime version');
  assert.equal(JSON.parse(runtimeVersion[1]),version,'Banner and runtime versions must agree');
  const outputs = Object.values(result.metafile.outputs);
  assert.equal(outputs.length,1);
  assert.equal(outputs[0].imports.length,0,'Production must not load external chunks');
  for (const [input,details] of Object.entries(result.metafile.inputs)) {
    assert(input.startsWith('src/'),'Build inputs must be maintained under src/: '+input);
    if (input.startsWith('src/common/')) {
      assert(!details.imports.some(dependency=>dependency.path.startsWith('src/WebPage/')),
        'Common modules must not import page implementations: '+input);
    }
  }
  for (const page of pages) {
    assert(result.metafile.inputs['src/WebPage/'+page+'/module.js'],'Missing production page: '+page);
    const debug = await build({page,write:false,version});
    assert.equal(debug.outputFiles.length,1,'Single-page build must be one file: '+page);
    new vm.Script(debug.outputFiles[0].text,{filename:page+'.js'});
    const modules = Object.keys(debug.metafile.inputs).filter(input=>input.startsWith('src/WebPage/')&&input.endsWith('/module.js'));
    assert.deepEqual(modules,['src/WebPage/'+page+'/module.js'],'Single-page build must isolate its page: '+page);
  }
  const report = {status:'PASS',scope:'Build integrity only; no browser, live-site or PotPlayer verification',
    version,pageModules:pages.length,productionBytes:Buffer.byteLength(source),productionOutputs:1,
    sha256:crypto.createHash('sha256').update(source).digest('hex'),debugBuilds:pages.length};
  fs.mkdirSync(path.join(root,'verification'),{recursive:true});
  fs.writeFileSync(path.join(root,'verification/build-check.json'),JSON.stringify(report,null,2)+'\n');
  console.log(report);
  return report;
}
module.exports={build,options,pages,check,localVersion,releaseVersion};
async function main() {
  const args=process.argv.slice(2);
  let page,all=false,watch=false,checking=false,release=false;
  for(let i=0;i<args.length;i++) {
    if(args[i]==='--page') {page=args[++i];if(!page||page.startsWith('--'))throw Error('--page requires a page ID');}
    else if(args[i]==='--all-pages')all=true;
    else if(args[i]==='--watch')watch=true;
    else if(args[i]==='--check')checking=true;
    else if(args[i]==='--release')release=true;
    else throw Error('Unknown argument: '+args[i]);
  }
  if(all&&(page||watch))throw Error('--all-pages cannot be combined with --page or --watch');
  if(checking&&(page||all||watch))throw Error('--check cannot be combined with --page, --all-pages or --watch');
  if(release&&(page||all||watch))throw Error('--release cannot be combined with --page, --all-pages or --watch');
  if(checking) { await check({release}); return; }
  if(all)for(const id of pages)await build({page:id});
  else if(watch) {
    const settings=options(page);
    settings.plugins.push({name:'build-report',setup(build) {
      build.onEnd(result=>{if(!result.errors.length)writeMetafile(page,result);});
    }});
    const context=await esbuild.context(settings);await context.watch();
    console.log('Watching '+(page||'production')+'. Press Ctrl+C to stop.');return;
  } else await build({page,version:release?releaseVersion():undefined});
  console.log('Built '+(page?'debug/'+page+'.js':all?'all debug pages':'BroadcastListScript.js'));
}
if(require.main===module)main().catch(error=>{console.error(error);process.exitCode=1;});
